import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {extractPdf} from '../desktop/pdf-import';
import {RulesStore} from '../desktop/rules-store';
import {referenceOf,validRuleReferences} from '../lib/rules';
import {pdfFixture} from './pdf-fixture';
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'waypoint-pdf-test-'));
const worker=path.resolve('desktop/build/pdf-worker.mjs');
const file=path.join(directory,'Moonstone.pdf');fs.writeFileSync(file,pdfFixture());
const progress:number[]=[];
const result=await extractPdf(file,p=>progress.push(p.page),worker,'off');
assert.equal(result.pages,1);assert.equal(result.skipped,0);assert.deepEqual(progress,[1]);
assert.match(result.entries[0].body,/silver key/);assert.equal(result.entries[0].page,'1');
assert(validRuleReferences([referenceOf(result.entries[0])]));
let store=new RulesStore(directory);store.importEntries(result.entries);
assert.equal(store.search({kind:'PDF page',query:'silver key'}).total,1);
store.importEntries((await extractPdf(file,()=>{},worker)).entries);
assert.equal(store.search({}).total,1,'Reimport must not duplicate passages');
store.close();store=new RulesStore(directory);assert.match(store.get(result.entries[0].id).body,/Moonstone/);store.close();
fs.writeFileSync(file,pdfFixture('',true));await assert.rejects(extractPdf(file,()=>{},worker),/OCR/);
fs.writeFileSync(file,'not a PDF');await assert.rejects(extractPdf(file,()=>{},worker));
fs.writeFileSync(file,pdfFixture('Ancient rune '.repeat(900)));
const long=await extractPdf(file,()=>{},worker);assert(long.entries.length>1);assert(long.entries.every(e=>e.body.length<=6500));assert(long.entries.every(e=>validRuleReferences([referenceOf(e)])));
const scanned=path.resolve('desktop/build/data/ocr-smoke.pdf');
await assert.rejects(extractPdf(scanned,()=>{},worker,'off'),/readable text/);
const recognized=await extractPdf(scanned,()=>{},worker,'auto');
assert.equal(recognized.ocrPages,1);assert.match(recognized.entries[0].body,/silver key/i);assert(recognized.entries[0].warnings.some(w=>w.includes('OCR text')));
store=new RulesStore(directory);store.importPdf(recognized.entries);store.importPdf(recognized.entries);assert.equal(store.search({query:'silver key'}).total,2);store.close();
console.log('OCR passed: image-only PDF recognition, original page number, confidence warning and repeat import.');
console.log('PDF tests passed: text, pages, progress, search, pinning, deduplication, persistence, blank and damaged files, long-page splitting.');
